/**
 * Builds the registration receipt as a PDF in the browser. jsPDF is imported
 * on demand so it never ships with the receipt page itself.
 *
 * PDF can't read CSS variables, so the light-theme tokens are mirrored here
 * as RGB (see globals.css :root). Keep the two in sync.
 */
const C = {
  text: [15, 23, 42] as const, // --text
  muted: [71, 85, 105] as const, // --text-muted
  subtle: [93, 108, 131] as const, // --text-subtle
  border: [226, 232, 240] as const, // --border
  surface2: [241, 245, 249] as const, // --surface-2
  primary: [97, 100, 239] as const, // --primary
  success: [4, 120, 87] as const, // --success-text
}

export type ReceiptData = {
  receiptNumber: string
  eventName: string
  submittedAt: Date
  student: { name: string; registerNumber: string; email: string; department?: string; degree?: string; section?: string }
  electives: { groupName: string; electiveName: string }[]
}

export async function downloadReceiptPdf(data: ReceiptData) {
  const [{ default: jsPDF }, { default: autoTable }] = await Promise.all([import("jspdf"), import("jspdf-autotable")])
  const doc = new jsPDF({ unit: "mm", format: "a4" })
  const W = doc.internal.pageSize.getWidth()
  const M = 18
  let y = M

  // Brand mark: rounded square + check
  doc.setFillColor(...C.primary)
  doc.roundedRect(M, y, 10, 10, 2, 2, "F")
  doc.setDrawColor(255, 255, 255)
  doc.setLineWidth(0.9)
  doc.lines([[2.2, 2.2], [4.2, -4.6]], M + 2.6, y + 5.2)
  doc.setFont("helvetica", "bold")
  doc.setFontSize(13)
  doc.setTextColor(...C.text)
  doc.text("Electify", M + 13, y + 6.8)

  doc.setFont("helvetica", "normal")
  doc.setFontSize(9)
  doc.setTextColor(...C.muted)
  doc.text("Registration receipt", W - M, y + 3.5, { align: "right" })
  doc.setFont("courier", "bold")
  doc.setFontSize(11)
  doc.setTextColor(...C.text)
  doc.text(data.receiptNumber, W - M, y + 8.5, { align: "right" })

  y += 18
  doc.setDrawColor(...C.border)
  doc.setLineWidth(0.3)
  doc.line(M, y, W - M, y)

  // Status line
  y += 10
  doc.setFont("helvetica", "bold")
  doc.setFontSize(18)
  doc.setTextColor(...C.text)
  doc.text("Registration confirmed", M, y)
  y += 6.5
  doc.setFont("helvetica", "normal")
  doc.setFontSize(10)
  doc.setTextColor(...C.muted)
  doc.text(`${data.eventName}`, M, y)
  y += 5
  doc.text(
    `Confirmed ${data.submittedAt.toLocaleString("en-IN", { dateStyle: "long", timeStyle: "short", timeZone: "Asia/Kolkata" })} IST`,
    M,
    y
  )
  doc.setTextColor(...C.success)
  doc.setFont("helvetica", "bold")
  doc.text("Confirmed", W - M, y - 5, { align: "right" })

  // Student details
  y += 12
  const details: [string, string][] = [
    ["Name", data.student.name],
    ["Register number", data.student.registerNumber],
    ["Email", data.student.email],
  ]
  if (data.student.degree) details.push(["Programme", data.student.degree])
  if (data.student.department) details.push(["Department", data.student.department])
  if (data.student.section) details.push(["Section", data.student.section])

  doc.setFillColor(...C.surface2)
  const boxH = Math.ceil(details.length / 2) * 13 + 6
  doc.roundedRect(M, y, W - 2 * M, boxH, 3, 3, "F")
  const colW = (W - 2 * M) / 2
  details.forEach(([label, value], i) => {
    const cx = M + 6 + (i % 2) * colW
    const cy = y + 9 + Math.floor(i / 2) * 13
    doc.setFont("helvetica", "normal")
    doc.setFontSize(8)
    doc.setTextColor(...C.subtle)
    doc.text(label, cx, cy)
    doc.setFont(label === "Register number" ? "courier" : "helvetica", "bold")
    doc.setFontSize(10.5)
    doc.setTextColor(...C.text)
    doc.text(doc.splitTextToSize(value, colW - 10)[0] ?? "", cx, cy + 5)
  })
  y += boxH + 10

  // Electives
  doc.setFont("helvetica", "bold")
  doc.setFontSize(11)
  doc.setTextColor(...C.text)
  doc.text("Electives", M, y)
  autoTable(doc, {
    startY: y + 3,
    margin: { left: M, right: M },
    head: [["Group", "Elective"]],
    body: data.electives.map((e) => [e.groupName, e.electiveName]),
    theme: "plain",
    styles: { font: "helvetica", fontSize: 10, textColor: [...C.text], cellPadding: { top: 3.5, bottom: 3.5, left: 3, right: 3 }, lineColor: [...C.border], lineWidth: { bottom: 0.3 } },
    headStyles: { fontSize: 8.5, fontStyle: "normal", textColor: [...C.subtle], lineWidth: { bottom: 0.3 } },
    columnStyles: { 0: { cellWidth: 70, textColor: [...C.muted] }, 1: { fontStyle: "bold" } },
  })

  // Footer
  const pageH = doc.internal.pageSize.getHeight()
  doc.setFont("helvetica", "normal")
  doc.setFontSize(8)
  doc.setTextColor(...C.subtle)
  doc.text(`Computer generated receipt for ${data.eventName}. Generated by Electify.`, M, pageH - 14)
  doc.text("Student signature", M, pageH - 26)
  doc.text("Authorised signatory", W - M, pageH - 26, { align: "right" })
  doc.setDrawColor(...C.border)
  doc.line(M, pageH - 30, M + 55, pageH - 30)
  doc.line(W - M - 55, pageH - 30, W - M, pageH - 30)

  doc.save(`Electify-receipt-${data.receiptNumber}.pdf`)
}
